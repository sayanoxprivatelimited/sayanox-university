const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm');
const store = new Map(), controls = {};
let writeFails = false;
const panel = {innerHTML:'', addEventListener(type, callback){this[type] = callback}, contains(){return false}};
const document = {getElementById(id){return id === 'studyDashboard' ? panel : (controls[id] ??= {focus(){this.focused = true}})}, addEventListener(){}, hidden:false};
const context = {document, window:{addEventListener(){}}, localStorage:{getItem:k=>store.get(k) ?? null, setItem(k,v){if(writeFails) throw Error('full'); store.set(k,v)}}, Date, Number, String, Array, Object, Math, setInterval, clearInterval};
vm.createContext(context);
vm.runInContext(`const courses = [{id:'one',lessons:[0,1,2]},{id:'two',lessons:[0,1]}]; let progress = {}; let quizScores = {}; const quizzes = {one:[1,2],two:[1,2]}; function doneFor(c){return progress[c.id] || []}`,context);
vm.runInContext(fs.readFileSync('study.js','utf8'),context);
const run = s => vm.runInContext(s,context);
assert.equal(run('weeklyGoal'),5);
assert.equal(run('studyRewards().xp'),0);
assert.equal(run('studyRewards().level'),1);
assert.equal(run('studyWeek(new Date(2024, 1, 29)).map(d => d.day).join(",")'),'2024-02-26,2024-02-27,2024-02-28,2024-02-29,2024-03-01,2024-03-02,2024-03-03');
assert.equal(run('studyWeek(new Date(2024, 2, 3))[0].day'),'2024-02-26');
assert.equal(run('studyWeek(new Date(2024, 2, 4))[0].day'),'2024-03-04');
run("studyData.days = {'2024-02-26':{lessons:2,seconds:0,met:true},'2024-03-01':{lessons:7,seconds:0,met:true}}");
assert.equal(run('studyWeek(new Date(2024,1,29)).reduce((s,d)=>s+d.lessons,0)'),2); // Future records aren't counted.
run("progress.one=[0,1,2]; quizScores.two=2");
assert.equal(run('studyRewards().xp'),30);
assert.equal(run('studyRewards().finished'),1);
assert.equal(run('studyRewards().achievements.filter(a=>a.earned).length'),3);
run('progress.one=[]; quizScores.two=0');
assert.equal(run('studyRewards().xp'),0); // A reset removes derived XP and badges.
run("courses.push({id:'ten',lessons:Array.from({length:10},(_,i)=>i)}); quizzes.ten=[1]; progress.ten=Array.from({length:10},(_,i)=>i)");
assert.equal(run('studyRewards().xp'),100); assert.equal(run('studyRewards().level'),2); assert.equal(run('studyRewards().next'),100);
run('courses.pop(); delete progress.ten; delete quizzes.ten');
assert.equal(run('studyWeek(new Date(2024,2,10)).map(d=>d.day).join(",")'),'2024-03-04,2024-03-05,2024-03-06,2024-03-07,2024-03-08,2024-03-09,2024-03-10');
run('studyData.days = {}; recordStudyLesson(); recordStudyLesson()');
assert.equal(run('todayStudy().lessons'),2);
assert.equal(run('todayStudy().met'),true);
panel.change({target:{id:'dailyGoal',value:'3'}});
assert.equal(run('todayStudy().met'),false);
assert.equal(controls.dailyGoal.focused,true);
panel.change({target:{id:'weeklyGoal',value:'14'}});
assert.equal(store.get('sayanox-weekly-goal'),'14');
assert.equal(run('weeklyGoal'),14);
assert(panel.innerHTML.includes('14 lesson completion events'));
assert.equal(controls.weeklyGoal.focused,true);
panel.change({target:{id:'weeklyGoal',value:'36'}});
assert.equal(run('weeklyGoal'),14);
store.set('sayanox-weekly-goal','<img>'); run('loadWeeklyGoal()'); assert.equal(run('weeklyGoal'),5);
store.set('sayanox-weekly-goal','35'); run('loadWeeklyGoal()'); assert.equal(run('weeklyGoal'),35);
writeFails = true; panel.change({target:{id:'weeklyGoal',value:'6'}}); assert(controls.studySaveStatus.textContent.includes('Weekly goal could not be saved'));
run('recordStudyLesson()'); assert(controls.studySaveStatus.textContent.includes('Study data could not be saved'));
run('todayStudy().lessons=10000; recordStudyLesson()'); assert.equal(run('todayStudy().lessons'),10000);
console.log('Study goals, calendar, rewards and storage tests passed.');
